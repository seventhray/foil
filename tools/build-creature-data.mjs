/**
 * tools/build-creature-data.mjs
 * Writes src/creature-data.js from the GMG: Natural Weapons (9.6.1), Monster Feats (9.5.1),
 * and Traits (9.5.0). The Creature Generator reads it.
 */

import fs from "node:fs";
import path from "node:path";
import { readGMG, readPHB, readCatalog, cells, sectionText, SYSTEM_ROOT } from "./books.mjs";

const clean = s => String(s ?? "").replace(/\*\*/g, "").replace(/\[\[[^\]]*\|([^\]]*)\]\]/g, "$1").replace(/\[\[#?([^\]]*)\]\]/g, "$1").replace(/\s+/g, " ").trim();
const lc = s => String(s).toLowerCase();

function rowsAfter(lines, startIdx) {
  const rows = [];
  let i = startIdx;
  while (i < lines.length && !lines[i].trim().startsWith("|")) i++;
  const header = cells(lines[i]);
  for (i += 2; i < lines.length && lines[i].trim().startsWith("|"); i++) {
    const c = cells(lines[i]);
    rows.push(Object.fromEntries(header.map((h, k) => [h, c[k] ?? ""])));
  }
  return rows;
}

export function buildCreatureData() {
  const GMG = readGMG();

  // Natural Weapons: one table per bold group heading.
  const nw = [];
  const body = sectionText(GMG, /^### 9\.6\.1 Natural Weapons/).split("\n");
  let group = "";
  body.forEach((line, i) => {
    const g = line.match(/^\*\*(Melee|Grappling|Arcane|Ranged|Sonic)\*\*\s*$/);
    if (!g) return;
    group = lc(g[1]);
    for (const r of rowsAfter(body, i)) {
      const names = clean(r["Natural Weapon"]).replace(/\s*\([^)]*\)/g, "").split(/,\s*(?:or\s+)?|\s+or\s+/).map(x => x.trim()).filter(Boolean);
      const typeText = clean(r["Instrument Types"]);
      const pick = /pick one/i.test(typeText);
      const types = typeText.replace(/\s*\(pick one\)/i, "").split(/,\s*|\s+or\s+/).map(x => lc(x.trim())).filter(Boolean);
      const range = clean(r.Range);
      for (const name of names) nw.push({ name, group, types, pick, range });
    }
  });

  // Monster Feats.
  const sec = sectionText(GMG, /^### 9\.5\.1 Monster Feats/).split("\n");
  const feats = rowsAfter(sec, 0).map(r => {
    const xpText = clean(r.XP);
    const base = Number(xpText.match(/\d+/)?.[0] ?? 0);
    const per = (xpText.match(/per (use|Condition|point|\+1)/i)?.[1] ?? "").toLowerCase();
    return { name: clean(r.Feat), xp: base, per, xpText, requires: clean(r.Requirements), effect: clean(r.Effect) };
  });

  // Traits (the table before 9.5.1).
  const top = sectionText(GMG, /^## 9\.5\.0 Feats and Traits/).split("\n");
  // Each Trait's text: the PHB Traits table for senses and the like, the Catalog Technique of the same name for movement.
  const phbTraits = sectionText(readPHB(), /^### 7\.2\.3 Traits/).split("\n").filter(l => l.trim().startsWith("|")).slice(2).map(cells);
  const catalog = readCatalog().techniques;
  const AMPHIBIOUS = "Moves through water at full speed, as Swim does, and breathes water.";
  const describe = name => {
    if (name === "Amphibious") return AMPHIBIOUS;
    if (name === "Swim") return "Moves through water at full speed.";
    // A creature-only Trait is described in the GMG, as a sentence that opens "<name> needs".
    const own = top.join(" ").match(new RegExp(`${name} needs [^.]+\\.\\s+([^.]+\\.)`));
    if (own) return own[1];
    const row = phbTraits.find(c => clean(c[0]).split(/,\s*(?:or\s+)?|\s+or\s+/).includes(name) || clean(c[0]) === name);
    if (row) return clean(row[4]);
    const tech = catalog.find(t => t.name === name);
    return tech ? clean(tech.effect) : "";
  };
  const traits = rowsAfter(top, 0).map(r => ({ name: clean(r.Trait), xp: Number(clean(r["Allowance Cost"])) || 0, effect: describe(clean(r.Trait)) }));

  const file = path.join(SYSTEM_ROOT, "src", "creature-data.js");
  fs.writeFileSync(file, "/** Generated by tools/build-creature-data.mjs from the GMG (9.5.0, 9.5.1, 9.6.1). Do not edit. */\n"
    + `export const NATURAL_WEAPONS = ${JSON.stringify(nw, null, 1)};\nexport const MONSTER_FEATS = ${JSON.stringify(feats, null, 1)};\nexport const TRAITS = ${JSON.stringify(traits, null, 1)};\n`);
  return { nw: nw.length, feats: feats.length, traits: traits.length };
}

if (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href) console.log(buildCreatureData());
