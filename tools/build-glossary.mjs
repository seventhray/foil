/**
 * tools/build-glossary.mjs
 * Writes src/glossary.js: a definition for every keyword the sheets can show,
 * taken from the PHB (Key Terms, Instrument Types, Conditions, weight classes)
 * and Fundamental Math (Technique Effects, Patterns).
 */

import fs from "node:fs";
import path from "node:path";
import { readPHB, readFM, tableAfter, sectionText, SYSTEM_ROOT } from "./books.mjs";

const clean = s => String(s ?? "")
  .replace(/\[\[[^\]]*\|([^\]]*)\]\]/g, "$1").replace(/\[\[#?([^\]]*)\]\]/g, "$1")
  .replace(/\s*\((?:see|See) [^)]*\)/g, "")
  .replace(/<br\s*\/?>/gi, " ").replace(/\*\*([^*]+)\*\*/g, "$1").replace(/\*([^*]+)\*/g, "$1")
  .replace(/\s+/g, " ").trim();

export function buildGlossary() {
  const PHB = readPHB(), FM = readFM();
  const out = {};
  const add = (name, text, overwrite = false) => {
    const key = clean(name).toLowerCase();
    const body = clean(text);
    if (!key || !body || key.length < 3) return;
    if (!overwrite && out[key]) return;
    out[key] = { name: clean(name), text: body };
  };

  for (const r of tableAfter(PHB, /^# Key Terms and Definitions/)) add(r.Term.replace(/\s*\(.*\)$/, ""), r.Definition);

  // Instrument Types (PHB 4.1.1): every table row under the heading.
  for (const line of sectionText(PHB, /^### 4\.1\.1 Instrument Types/).split("\n")) {
    const c = line.split("|").map(x => x.trim()).filter((x, i, a) => !(i === 0 && x === "") && !(i === a.length - 1 && x === ""));
    if (line.trim().startsWith("|") && c.length >= 2 && !/^[-: ]+$/.test(c[0]) && c[0] !== "Type") add(c[0].replace(/\s*\[.*\]$/, ""), c[1], true);
    const w = line.match(/^- \*\*(Light|Medium|Heavy)\*\*: (.+)$/);
    if (w) add(`${w[1]} Instrument`, w[2]), add(w[1], w[2]);
  }

  // Conditions (PHB 6.8.x).
  const cond = sectionText(PHB, /^## 6\.8\.0 Conditions and Defeat/);
  for (const block of cond.split(/\n(?=### 6\.8\.\d+ )/).slice(1)) {
    const m = block.match(/^### 6\.8\.\d+ (\w+)\s*\n([\s\S]*)$/);
    if (m) add(m[1], m[2].replace(/\n+/g, " "), true);
  }

  // Technique Effects (Fundamental Math), under their short names.
  for (const r of tableAfter(FM, /^## Technique Effects/)) {
    const raw = clean(r.Effect);
    const name = raw.replace(/\[.*?\]|\(.*?\)/g, "").replace(/\s+(N|Xd4|\+N|-N)\b.*$/, "").replace(/^[+-]N\s*/, "").trim();
    if (/^[+-]?\d|^Condition$|^$/.test(name)) continue;
    add(name, r.Description);
  }
  add("Hasten", "Grant the target an extra Action or Quick Action on its next turn.");

  // Patterns.
  for (const line of sectionText(FM, /^## Patterns/).split("\n")) {
    const m = line.match(/^- \*\*(Beam|Cone|Radius|Wall)\*\*: (.+)$/);
    if (m) add(m[1], m[2], true);
  }

  const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
  const file = path.join(SYSTEM_ROOT, "src", "glossary.js");
  fs.writeFileSync(file, `/** Generated by tools/build-glossary.mjs from the PHB and Fundamental Math. Do not edit. */\nexport const GLOSSARY = ${JSON.stringify(sorted, null, 2)};\n`);
  return Object.keys(sorted).length;
}

if (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href) console.log(`${buildGlossary()} terms`);
